  function applyLanguage(lang) {
    if (!SUPPORTED_LANGS.includes(lang)) lang = 'ar';
    currentLang = lang;
    try {
      localStorage.setItem('ehky-lang', lang);
    } catch {}

    const isRtl = lang === 'ar';
    document.documentElement.setAttribute('dir', isRtl ? 'rtl' : 'ltr');
    document.documentElement.setAttribute('lang', lang);
    document.body.classList.toggle('lang-ltr', !isRtl);

    // Translate static [data-i18n] elements (nav links, footer, labels)
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.ar;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = dict[key] || TRANSLATIONS.ar[key];
      if (val) el.textContent = val;
    });

    window.dispatchEvent(new CustomEvent('ehkyLanguageChanged', { detail: { lang } }));
  }

  // Initialize
  applyLanguage(currentLang);

  window.I18N = {
    get current() {
      return currentLang;
    },
    get isRtl() {
      return currentLang === 'ar';
    },
    t(key) {
      const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.ar;
      return dict[key] || TRANSLATIONS.ar[key] || key;
    },
    setLanguage(lang) {
      applyLanguage(lang);
    },
    getSupported() {
      return [
        { code: 'ar', label: 'العربية', flag: '🇪🇬' },
        { code: 'en', label: 'English', flag: '🇬🇧' },
        { code: 'fr', label: 'Français', flag: '🇫🇷' },
        { code: 'it', label: 'Italiano', flag: '🇮🇹' },
        { code: 'de', label: 'Deutsch', flag: '🇩🇪' }
      ];
    }
  };
